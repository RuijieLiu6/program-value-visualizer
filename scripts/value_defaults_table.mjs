// Writes docs/value_defaults.md: the default value per m2 GFA of every programme, with its basis and source.
// Usage: node scripts/value_defaults_table.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const J = rel => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const P = 'packs/vancouver-2026/';
const progs = J('catalogue/programmes.json').programmes;
const fams = new Map(J('catalogue/families.json').families.map(f => [f.family_id, f]));
const rows = new Map(J(P + 'values.json').rows.map(r => [r.id, r]));
const sources = new Map(J(P + 'sources.json').sources.map(s => [s.id, s]));

const N = x => Math.round(x).toLocaleString('en-CA');
const pct = x => `${+(x * 100).toFixed(2)}%`;
const cell = s => String(s ?? '').replace(/\|/g, '/').replace(/\s+/g, ' ').trim();
const BASIS = { sourced: 'sourced', researched: 'researched', analogy: 'analogy', no_income: 'earns nothing' };

/** One line in the pack's formula style, from the row's stored inputs. */
function derivation(r) {
  const i = Object.fromEntries(Object.entries(r.inputs || {}).map(([k, x]) => [k, x.value]));
  switch (r.method) {
    case 'sale': return `sale: $${N(i.sale_price_per_ft2_net)}/ft² net × 10.764 × ${i.efficiency} eff. × (1 − ${pct(i.selling_cost ?? 0)} selling)`;
    case 'income': {
      const rent = i.rent_per_ft2_net_year != null ? `$${i.rent_per_ft2_net_year}/ft²/yr` : `$${i.rent_per_ft2_net_month}/ft²/month`;
      const parts = [rent, i.vacancy != null && `${pct(i.vacancy)} vacant`, i.leakage && `${pct(i.leakage)} leakage`, i.opex_ratio && `${pct(i.opex_ratio)} costs`, i.opex_per_ft2_year && `$${i.opex_per_ft2_year}/ft² costs`].filter(Boolean);
      return `income: ${parts.join(', ')}; ÷ ${pct(i.cap_rate)} cap × ${i.efficiency} eff.`;
    }
    case 'per_key': return `per key: $${N(i.adr)} × ${pct(i.occupancy)} → NOI $${N(i.noi_per_key)}/key ÷ ${pct(i.cap_rate)} cap ÷ ${i.m2_per_key} m²/key`;
    case 'visitors': return `visitors: ${N(i.visitors_per_year)} × $${i.ticket_price} × (1 + ${pct(i.fnb_uplift ?? 0)} F&B) × ${pct(i.operating_margin)} margin ÷ ${pct(i.cap_rate)} cap ÷ ${N(i.deck_area_m2)} m²`;
    case 'per_stall_sale': return `stall sale: $${N(i.price_per_stall)} ÷ ${i.m2_per_stall} m²/stall`;
    case 'per_stall_income': return `stall income: $${i.rate_per_stall_month}/month × 12 × ${pct(i.utilisation)} used × ${pct(i.operating_margin)} margin ÷ ${pct(i.cap_rate)} cap ÷ ${i.m2_per_stall} m²/stall`;
    case 'stated': return `stated value${i.cap_rate ? ` (cap ${pct(i.cap_rate)})` : ''}; no income inputs`;
    case 'none': return 'no income to the owner';
    default: return r.method;
  }
}

const out = [];
const counts = { sourced: 0, researched: 0, analogy: 0, 'earns nothing': 0 };
for (const p of progs) {
  const row = p.value_status === 'linked' ? rows.get(p.value_ref) : null;
  const v = row?.value_per_m2_gfa;
  let basis = row ? BASIS[row.value_basis] : 'earns nothing';
  if (row && row.value_basis === 'sourced' && v.value === 0) basis = 'earns nothing';
  counts[basis]++;
  const s = v ? sources.get(v.source) : null;
  const src = !row ? 'support space (catalogue)' : !s || s.id === 'assumption' ? 'author assumption' : `${s.publisher ? s.publisher + ', ' : ''}${s.title}`;
  const date = !row ? '—' : s && s.id !== 'assumption' ? (s.published || 'n.d.') : v.as_of;
  const range = v?.range ? `${N(v.range[0])}–${N(v.range[1])}` : '—';
  const deriv = row ? derivation(row) : 'support space: earns nothing, costed with its floor';
  out.push(`| ${p.id} | ${cell(p.name)} | ${row ? N(v.value) : 0} | ${range} | ${basis} | ${cell(src)} | ${cell(date)} | ${row ? v.grade : '—'} | ${cell(deriv)}${row ? ` (row ${row.id})` : ''} |`);
}

const md = `# Default value per m² GFA, all programmes

Generated by \`node scripts/value_defaults_table.mjs\` from the catalogue and the Vancouver 2026 pack. Do not edit by hand.

Value per m² of gross floor area, before the height premium and, for office-type rows, before leasing costs. Indicative early-design estimates, not appraisals.

**Basis**
- **sourced**: the pack's original row, from cited market inputs and the author's stated assumptions.
- **researched**: a typical estimate built from a 2025–26 Vancouver, BC or Canadian figure found by web search on 18 Oct 2026. Most searches returned summaries rather than full reports, so these stay grade C.
- **analogy**: a typical estimate borrowed from a similar use, because no usable figure was found. The note in the pack says what was searched.
- **earns nothing**: public, civic or support space with no income to the owner (cost only).

The grade is that of the weakest key input (A best, C weakest). "Main source" is the source of the value itself; each input carries its own source in \`packs/vancouver-2026/values.json\`.

Counts: ${Object.entries(counts).map(([k, n]) => `${n} ${k}`).join(' · ')} (${progs.length} programmes).

| ID | Programme | C$/m² GFA | Range | Basis | Main source | Date | Grade | Derivation |
| --- | --- | ---: | --- | --- | --- | --- | --- | --- |
${out.join('\n')}

Notes on the families: ${[...fams.values()].map(f => `${f.family_id} ${f.name}`).join(' · ')}.
`;
fs.writeFileSync(path.join(ROOT, 'docs/value_defaults.md'), md);
console.log('docs/value_defaults.md:', progs.length, 'programmes;', JSON.stringify(counts));
