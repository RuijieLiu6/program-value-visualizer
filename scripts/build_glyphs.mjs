// Build app/icons/glyphs.js (GPT-drawn icon glyphs) and app/icons/ui_icons.js (Phosphor button icons).
// Usage: node scripts/build_glyphs.mjs [glyph-svg-dir] [phosphor-assets-dir]
// Glyph SVGs come from the icon pipeline in ~/Desktop/program-icons/chatgpt (GPT sheets -> slice -> vtracer):
// one file per id, 256 x 256 canvas, paths of absolute M/C/Z, each wrapped in translate(x,y).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HOME = process.env.HOME;
const GLYPH_DIR = process.argv[2] || path.join(HOME, 'Desktop/program-icons/chatgpt/svg');
const PH_DIR = process.argv[3] || path.join(HOME, 'Desktop/program-icons/vendor/phosphor-core/package/assets/regular');

/** One glyph file -> one compact path: offsets applied, whole-pixel coordinates, straight curves as lines. */
function compactGlyph(svg) {
  const parts = [];
  for (const m of svg.matchAll(/<path d="([^"]+)"\s*transform="translate\((-?[\d.]+),(-?[\d.]+)\)"\s*\/>/g)) {
    const tx = +m[2], ty = +m[3];
    const toks = m[1].match(/[MCZ]|-?\d*\.?\d+(?:e-?\d+)?/g);
    let i = 0, cur = null;
    const segs = [];   // {t:'M'|'L'|'C'|'Z', from, pts}
    const num = () => +toks[i++];
    const pt = () => [Math.round(num() + tx), Math.round(num() + ty)];
    while (i < toks.length) {
      const c = toks[i++];
      if (c === 'M') { const p = pt(); segs.push({ t: 'M', pts: [p] }); cur = p; }
      else if (c === 'C') {
        const a = pt(), b = pt(), p = pt();
        // control points on the chord (within half a pixel) -> a straight line
        const dx = p[0] - cur[0], dy = p[1] - cur[1], len = Math.hypot(dx, dy);
        const off = q => len ? Math.abs((q[0] - cur[0]) * dy - (q[1] - cur[1]) * dx) / len : Math.hypot(q[0] - cur[0], q[1] - cur[1]);
        if (off(a) <= 0.5 && off(b) <= 0.5) {
          if (!len) continue;
          const prev = segs.at(-1);
          // same direction as the previous line -> extend it
          if (prev.t === 'L' && Math.abs((prev.pts[0][0] - prev.from[0]) * dy - (prev.pts[0][1] - prev.from[1]) * dx) < 1e-9 && (prev.pts[0][0] - prev.from[0]) * dx + (prev.pts[0][1] - prev.from[1]) * dy > 0) prev.pts[0] = p;
          else segs.push({ t: 'L', from: cur, pts: [p] });
        } else segs.push({ t: 'C', from: cur, pts: [a, b, p] });
        cur = p;
      } else if (c === 'Z') { segs.push({ t: 'Z' }); }
      else throw new Error(`unexpected path command ${c}`);
    }
    const rel = (q, o) => `${q[0] - o[0]} ${q[1] - o[1]}`;
    const out = segs.map(s => s.t === 'M' ? `M${s.pts[0][0]} ${s.pts[0][1]}` : s.t === 'Z' ? 'z' : s.t === 'L' ? `l${rel(s.pts[0], s.from)}` : `c${s.pts.map(q => rel(q, s.from)).join(' ')}`).join('');
    parts.push(out.replace(/ -/g, '-'));
  }
  if (!parts.length) throw new Error('no paths');
  return parts.join('');
}

const files = fs.readdirSync(GLYPH_DIR).filter(f => /^[A-Za-z0-9]+\.svg$/.test(f)).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
const glyphs = Object.fromEntries(files.map(f => [f.replace('.svg', ''), compactGlyph(fs.readFileSync(path.join(GLYPH_DIR, f), 'utf8'))]));
const gjs = `// Program Value Visualizer — icon glyphs: one per programme and per money symbol.
// Drawn by GPT (gpt-6-astra via Codex) from a written style brief, traced to vector with vtracer (MIT).
// Generated by scripts/build_glyphs.mjs — do not edit by hand. 256 x 256 canvas, glyph within the middle 70%.
export const GLYPH_BOX = 256;
export const GLYPHS = {
${Object.entries(glyphs).map(([k, d]) => `  ${/^[a-z]/.test(k) ? k : `'${k}'`}: '${d}',`).join('\n')}
};
`;
fs.writeFileSync(path.join(ROOT, 'app/icons/glyphs.js'), gjs);

// Phosphor icons for buttons and tabs (regular weight). Keep this list in step with app/app.js BUTTON_ICONS / TAB_ICONS.
const UI = ['buildings', 'magic-wand', 'question', 'arrow-counter-clockwise', 'circle-half', 'stack', 'building-office', 'file-csv',
  'seal-check', 'rows', 'bank', 'map-trifold', 'chart-bar-horizontal', 'sliders-horizontal', 'chat-circle-dots', 'book-open-text',
  'floppy-disk', 'export', 'download-simple', 'upload-simple', 'sparkle', 'lightbulb', 'pencil-simple', 'lock', 'lock-open', 'play',
  'stop', 'info', 'eye-slash', 'arrow-left', 'trash', 'crosshair', 'arrows-out', 'x', 'check', 'list-checks', 'paper-plane-right',
  'arrow-u-up-left', 'eraser', 'magnifying-glass', 'image', 'calculator'];
const ui = Object.fromEntries(UI.map(n => {
  const s = fs.readFileSync(path.join(PH_DIR, `${n}.svg`), 'utf8');
  const ds = [...s.matchAll(/<path d="([^"]+)"/g)].map(m => m[1]);
  if (!ds.length || /<(circle|rect|line|polyline|polygon)/.test(s)) throw new Error(`${n}: unexpected markup`);
  return [n, ds.join('')];
}));
const ujs = `// Program Value Visualizer — button and tab icons from Phosphor Icons 2.1.1 (regular weight).
// Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons — https://phosphoricons.com
// Generated by scripts/build_glyphs.mjs — do not edit by hand. 256 x 256 viewBox, filled with currentColor.
export const UI_ICONS = {
${Object.entries(ui).map(([k, d]) => `  '${k}': '${d}',`).join('\n')}
};

/** One button icon as an SVG string; decorative (the button's text names the action). */
export function uiIcon(name, size = 16) {
  const d = UI_ICONS[name];
  if (!d) throw new Error(\`unknown UI icon \${name}\`);
  return \`<svg class="bi" viewBox="0 0 256 256" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true" focusable="false"><path d="\${d}"/></svg>\`;
}
`;
fs.writeFileSync(path.join(ROOT, 'app/icons/ui_icons.js'), ujs);
console.log(`glyphs.js: ${Object.keys(glyphs).length} glyphs, ${(gjs.length / 1024).toFixed(0)} KB · ui_icons.js: ${UI.length} icons, ${(ujs.length / 1024).toFixed(0)} KB`);
